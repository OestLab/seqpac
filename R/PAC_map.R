PAC_map <- function(PAC, type="internal",  mapping="biotype",
                    output, input, bio_search=NULL, mismatches=3, 
                    save_name=FALSE, threads=1, override=FALSE, ...){

  import <- mapping
  reanno <- NULL
  
  if(mapping=="genome"){
    map_reanno(PAC=PAC, input=input, output=output, mismatches = mismatches, override=override, ...)
    reanno_obj<-make_reanno(PAC=PAC, reanno_path=output, ...)
    op <- add_reanno(reanno_obj, type=import, mismatches = mismatches)
    
  }
  
  if(mapping=="biotype"){
    map_reanno(PAC=PAC, input=input, output=output, mismatches = mismatches, override=override, ...)
    reanno_obj<-make_reanno(PAC=PAC, reanno_path=output, ...)
    
    if(!is.null(bio_search)){
    op <- add_reanno(reanno_obj, type=import, mismatches = mismatches,
                      bio_search = bio_search)
    }
    
    if(save_name==TRUE){
        
        level_obj <- as.list(reanno_obj@Full_anno)
        obj_names <- names(level_obj)
        obj_names <- obj_names[grepl("^mis\\d*$", obj_names)]
        
        if (length(obj_names) == 0) {
          stop("No mis-columns found on reanno object, please check whether mapping finalised correctly")
        }
        
        out_df <- data.frame(row.names = level_obj[[1]][[1]]$seq)
        all_df <- data.frame(row.names = level_obj[[1]][[1]]$seq)
        
        for (i in obj_names) {
          obj <- level_obj[[i]]
          list_names <- names(obj)
          
          for(j in list_names) {
            tib <- obj[[j]]
            if (ncol(tib) < 4) return(NULL)
            out <- tib[, 4, drop = FALSE]
            names(out) <- paste0(i, "_", j)
            out
            out_df <- cbind(out_df, out)
          }
          
          if(ncol(all_df)==0){
          all_df <- out_df
          }
          else{
            all_df <- cbind(all_df, out_df)
          }
        }
      
        
        if(!is.null(bio_search)){
      op <- cbind(op, all_df)
        }  else{
          op <- all_df
        }
      
    }
    
    
